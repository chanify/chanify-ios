#!/usr/bin/env python3
"""Generate the bundled offline policy from the sibling website's privacy.md."""
import argparse
import html
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="fail if the bundled copy is stale")
args = parser.parse_args()
repo = Path(__file__).resolve().parents[1]
source = repo.parent / "web/privacy.md"
target = repo / "iOS/Resources/Settings.bundle/Privacy.html"
text = source.read_text(encoding="utf-8")
if text.startswith("---\n"):
    text = text.split("---\n", 2)[2]

# The source uses only headings and paragraphs. Escape HTML and reject
# unsupported block syntax rather than silently losing policy text.
blocks = []
for block in text.strip().split("\n\n"):
    if block.startswith("## "):
        blocks.append("<h2>" + html.escape(block[3:]) + "</h2>")
    elif block.startswith("# "):
        blocks.append("<h1>" + html.escape(block[2:]) + "</h1>")
    elif block.startswith(("- ", "* ", "```", "<", "#")):
        raise SystemExit("Unsupported policy formatting: " + block.splitlines()[0])
    else:
        blocks.append("<p>" + html.escape(" ".join(block.splitlines())) + "</p>")

document = """<!doctype html>
<!-- Generated by Scripts/sync-privacy-policy.py; edit web/privacy.md. -->
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Chanify Privacy Policy</title>
<style>:root { color-scheme: light dark; } body { font: -apple-system-body;
line-height: 1.5; margin: 24px; overflow-wrap: anywhere; } h1 { font-size: 1.6em; }
h2 { font-size: 1.2em; } aside { opacity: .7; }</style></head><body>
<aside>This is the bundled offline copy. The latest policy is available at
<a href="https://www.chanify.net/privacy.html">www.chanify.net/privacy.html</a>.</aside>
""" + "\n".join(blocks) + "\n</body></html>\n"
if args.check:
    if not target.exists() or target.read_text(encoding="utf-8") != document:
        raise SystemExit("FAIL: offline policy is stale; run Scripts/sync-privacy-policy.py")
    print("PASS: offline policy matches web/privacy.md")
else:
    target.write_text(document, encoding="utf-8")
    print("Updated", target)
